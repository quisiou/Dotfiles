#!/bin/sh
# yazi/setup.sh


ROOT_DIR=$(cd "$(dirname "$0")" && pwd)
name=$(basename "$ROOT_DIR")

flag_force=false
flag_overwrite=false

for arg in "$@"; do
    case "$arg" in
        --"$name"-f) flag_force=true ;;
        --"$name"-o) flag_overwrite=true ;;
        --"$name"-*) echo "Warning: unrecognized flag '$arg' for $name" >&2 ;;
        *) ;;            # not my flag, ignore
    esac
done

link_file() {
    src=$1
    target=$2

    if [ "$flag_overwrite" = true ]; then
        rm -rf "$target"
    elif [ -L "$target" ] && [ ! -e "$target" ]; then
        rm "$target"    # dangling symlink, replace it
    fi

    if [ -L "$target" ]; then
        echo "    skipped    $target: file already exists (symlink)"
    elif [ -e "$target" ]; then
        echo "    skipped    $target: file already exists (not symlink)"
    else
        ln -s "$src" "$target"
        echo "    linked     $src -> $target"
    fi
}

merge_file() {
    default=$1
    user=$2
    target=$3

    GEN_MARK="# GENERATED by dotfiles setup. Do not edit; edit"

    if [ "$flag_overwrite" = true ]; then
        rm -rf "$target"
    elif [ -L "$target" ]; then
        rm "$target"    # old symlink from a previous setup, replace it
    fi

    # Regular file that we did not generate: leave it alone
    if [ -e "$target" ] && ! grep -q "^$GEN_MARK" "$target"; then
        echo "    skipped    $target: file already exists (not generated by setup)"
        return
    fi

    # Create the user file once, never overwrite it
    if [ ! -e "$user" ]; then
        : > "$user"
        echo "    created    $user"
    fi

    {
        echo "$GEN_MARK $(basename "$user")"
        cat "$user"
        echo
        cat "$default"
    } > "$target"
    echo "    merged     $(basename "$user") + $(basename "$default") -> $target"
}

echo "╔═══════════════════════════════╗"
echo "║ Setting up yazi configuration ║"
echo "╚═══════════════════════════════╝"
echo ""

. "$ROOT_DIR/../lib.sh" && require_dotfiles_home

CONFIG_DIR="$HOME/.config"
DEST="$CONFIG_DIR/yazi"

echo "Setting up $DEST/..."

if [ "$flag_force" = true ] || [ ! -e "$DEST" ]; then
    rm -rf "$DEST"
    mkdir -p "$DEST"
    echo "    created    $DEST/"
else
    echo "    skipped    $DEST/: file already exists"
fi

echo "╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌"

echo "Merging main configuration files..."

mkdir -p "$DEST/user"

merge_file "$ROOT_DIR/keymap.toml" "$DEST/user/keymap.toml" "$DEST/keymap.toml"
merge_file "$ROOT_DIR/yazi.toml" "$DEST/user/yazi.toml" "$DEST/yazi.toml"

echo "╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌"

echo "Linking color theme configuration file..."
link_file "$ELYSIAN_DOTS_HOME/active-theme/yazi.toml" "$DEST/theme.toml"

echo "╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌╌"

echo "Yazi configured successfully!"
